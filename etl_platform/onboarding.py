# The analytical contract is source-agnostic. Source adapters only define how
# a provider maps its records into this canonical staging/fact contract.
_CONTRACT_FIELDS = {"staging", "schema", "required", "dimensions", "facts"}
STANDARD_ANALYTICAL_CONTRACT = {
    domain: {
        key: deepcopy(value)
        for key, value in blueprint.items()
        if key in _CONTRACT_FIELDS
    }
    for domain, blueprint in _DOMAIN_BLUEPRINTS.items()
}
ODOO_ADAPTERS = {
    domain: {
        key: deepcopy(value)
        for key, value in blueprint.items()
        if key not in _CONTRACT_FIELDS
    }
    for domain, blueprint in _DOMAIN_BLUEPRINTS.items()
}
del _DOMAIN_BLUEPRINTS


def _source_contract(source_type, domain):
    if source_type != "ODOO":
        raise ValueError(f"Source adapter is not implemented: {source_type}")
    return {
        **deepcopy(STANDARD_ANALYTICAL_CONTRACT[domain]),
        **deepcopy(ODOO_ADAPTERS[domain]),
    }


def _load_template(environment):
    path = REPO_ROOT / "configs" / f"template_{environment}.yaml"
    with path.open("r", encoding="utf-8") as stream:
        return yaml.safe_load(stream)


def _yaml_text(document):
    return f"# {GENERATED_MARKER}\n" + yaml.safe_dump(document, sort_keys=False, allow_unicode=True)


def _write_generated(path, content, report, update=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        current = path.read_text(encoding="utf-8-sig")
        if current == content:
            report["unchanged"].append(str(path.relative_to(REPO_ROOT)))
            return
        if not update or GENERATED_MARKER not in current:
            report["preserved"].append(str(path.relative_to(REPO_ROOT)))
            return
        report["updated"].append(str(path.relative_to(REPO_ROOT)))
    else:
        report["created"].append(str(path.relative_to(REPO_ROOT)))
    path.write_text(content, encoding="utf-8")


